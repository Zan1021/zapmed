<?php

namespace App\Console\Commands;

use App\Models\BlogPost;
use Illuminate\Console\Command;
use Illuminate\Support\Facades\Http;

/**
 * Reconcile duplicate blog posts left over from an earlier partial import once
 * the canonical WordPress articles have been imported (php artisan blog:import-wp).
 *
 * For every group of published posts sharing a title, the post whose slug exists
 * in the live WordPress REST feed is kept as canonical; the others are archived
 * and a 301 redirect (retired slug → canonical slug) is written to
 * config/legacy_redirects.php so no ranking URL or internal link breaks.
 *
 *   php artisan blog:reconcile-duplicates --dry-run
 *   php artisan blog:reconcile-duplicates
 */
class ReconcileBlogDuplicates extends Command
{
    protected $signature = 'blog:reconcile-duplicates
                                {--source=https://zapmed.co.za : WordPress base URL (canonical slug source)}
                                {--dry-run : Report only, write nothing}';

    protected $description = 'Archive duplicate blog posts and 301 them to the canonical WordPress slug.';

    public function handle(): int
    {
        $dryRun = (bool) $this->option('dry-run');
        $base = rtrim($this->option('source'), '/');

        $wpSlugs = $this->fetchWpSlugs($base);
        if ($wpSlugs === null) {
            return self::FAILURE;
        }
        $this->info(count($wpSlugs) . ' canonical WP slugs loaded.');

        // Group published posts by normalised title.
        $groups = BlogPost::published()->get()->groupBy(fn ($p) => mb_strtolower(trim($p->title)));

        $redirects = [];
        $archived = 0;

        foreach ($groups as $title => $posts) {
            if ($posts->count() < 2) {
                continue;
            }

            // Canonical = the post whose slug is a real WP slug. Fall back to the
            // most-recently published if none match (shouldn't happen post-import).
            $canonical = $posts->firstWhere(fn ($p) => in_array($p->slug, $wpSlugs, true))
                ?? $posts->sortByDesc('published_at')->first();

            foreach ($posts as $post) {
                if ($post->id === $canonical->id) {
                    continue;
                }
                $redirects[$post->slug] = $canonical->slug;
                $this->line(sprintf('  archive %-55s -> %s', $post->slug, $canonical->slug));

                if (! $dryRun) {
                    $post->update(['status' => 'archived']);
                }
                $archived++;
            }
        }

        if (! $dryRun && $redirects) {
            $this->writeRedirectConfig($redirects);
        }

        $this->newLine();
        $this->info(sprintf(
            '%sarchived=%d redirects=%d published_now=%d',
            $dryRun ? '[dry-run] ' : '',
            $archived,
            count($redirects),
            BlogPost::published()->count()
        ));

        return self::SUCCESS;
    }

    /** @return array<int,string>|null */
    private function fetchWpSlugs(string $base): ?array
    {
        $slugs = [];
        $page = 1;
        do {
            $res = Http::acceptJson()->get("{$base}/wp-json/wp/v2/posts", [
                'per_page' => 100, 'page' => $page, '_fields' => 'slug',
            ]);
            if ($res->status() === 400) {
                break;
            }
            if (! $res->successful()) {
                $this->error("WP slug fetch failed page {$page}: HTTP {$res->status()}");
                return null;
            }
            $rows = $res->json();
            if (empty($rows)) {
                break;
            }
            foreach ($rows as $r) {
                $slugs[] = $r['slug'];
            }
            $page++;
        } while (true);

        return $slugs;
    }

    private function writeRedirectConfig(array $redirects): void
    {
        $path = config_path('legacy_redirects.php');

        // Merge with any existing entries so re-runs don't drop prior redirects.
        $existing = file_exists($path) ? (require $path) : [];
        $merged = array_merge($existing, $redirects);
        ksort($merged);

        $lines = ["<?php", "", "// Generated by `php artisan blog:reconcile-duplicates`.", "// retired slug => canonical slug (served at root). Used by App\\Support\\LegacyRedirects.", "return ["];
        foreach ($merged as $from => $to) {
            $lines[] = sprintf("    %s => %s,", var_export($from, true), var_export($to, true));
        }
        $lines[] = "];";
        $lines[] = "";

        file_put_contents($path, implode("\n", $lines));
        $this->info("Wrote " . count($merged) . " redirects to config/legacy_redirects.php");
    }
}
